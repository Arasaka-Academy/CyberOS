import { readFileSync, writeFileSync } from "node:fs";
import { appearanceSchemes, appearanceVariables, type AppearancePreference } from "../packages/shared/src/appearance.js";
import { createTheme } from "../packages/shared/src/cyberui-tokens.js";

const themes = appearanceSchemes.flatMap(scheme => (["dark", "light"] as const).map(mode => ({ scheme, mode })));
const css = "/* Generated by npm run appearance:generate from CyberUI v0.2.2. */\n" + themes.map(preference => {
  const selector = `${preference.scheme === "neon" && preference.mode === "dark" ? ":root, " : ""}:root[data-cyber-scheme='${preference.scheme}'][data-cyber-mode='${preference.mode}']`;
  return `${selector} {\n  color-scheme: ${preference.mode};\n${Object.entries(appearanceVariables(preference)).map(([key, value]) => `  ${key}: ${value};`).join("\n")}\n}`;
}).join("\n");
const native = Object.fromEntries(themes.map((preference: AppearancePreference) => [`${preference.scheme}/${preference.mode}`, createTheme(preference.scheme, preference.mode)]));
const assets = new Map([
  [new URL("../packages/shared/src/appearance.css", import.meta.url), css + "\n"],
  [new URL("../packages/shared/src/appearance-palettes.json", import.meta.url), JSON.stringify(native, null, 2) + "\n"]
]);
for (const [file, expected] of assets) {
  if (process.argv.includes("--check")) {
    if (readFileSync(file, "utf8") !== expected) throw new Error(`Stale appearance asset: ${file.pathname}`);
  } else writeFileSync(file, expected);
}
